// Each page gets one activity from every category; across the 10 pages every activity is shown once.
function shuffle(list) {
  const a = [...list];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
function buildPages() {
  const decks = Object.fromEntries(RIASEC_ORDER.map((t) => [t, shuffle(RIASEC_OPTIONS[t].map((_, i) => i))]));
  return Array.from({ length: RIASEC_PAGES }, (_, p) => shuffle(RIASEC_ORDER).map((t) => `${t}${decks[t][p]}`));
}
const itemOf = (key) => RIASEC_OPTIONS[key[0]][Number(key.slice(1))];

// Score = share of the maximum (10 activities × 5) for each type; top three, ties broken in RIASEC order.
function scoreRiasec(answers) {
  const totals = Object.fromEntries(RIASEC_ORDER.map((t) => [t, 0]));
  Object.entries(answers).forEach(([key, v]) => (totals[key[0]] += v));
  const scores = Object.fromEntries(RIASEC_ORDER.map((t) => [t, Math.round((totals[t] / (RIASEC_OPTIONS[t].length * 5)) * 100)]));
  const code = [...RIASEC_ORDER].sort((a, b) => scores[b] - scores[a] || RIASEC_ORDER.indexOf(a) - RIASEC_ORDER.indexOf(b)).slice(0, 3).join("");
  return { scores, code, completedAt: new Date() };
}


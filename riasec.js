// ---------- Render + events ----------
function renderRiasec(param) {
  closeAllOverlays();
  const r = state.riasec;
  if (param === "result") {
    if (!r.result) return go("riasec");
    riasecScreen.innerHTML = riasecResult();
    return;
  }
  const n = Number(param);
  if (n >= 1 && n <= RIASEC_PAGES) {
    if (!r.pages) return go("riasec");
    riasecScreen.innerHTML = riasecPage(n);
    return;
  }
  riasecScreen.innerHTML = riasecIntro();
}

const riasecStep = () => Number(location.hash.split("/")[1]) || 0;

riasecScreen.addEventListener("click", (e) => {
  const r = state.riasec;
  const rate = e.target.closest("[data-rate]");
  if (rate) {
    r.answers[rate.dataset.rate] = Number(rate.dataset.value);
    // Update just this question so the page doesn't jump.
    rate.parentElement.querySelectorAll(".likert__opt").forEach((b) => {
      const on = b === rate;
      b.classList.toggle("is-on", on);
      b.setAttribute("aria-checked", on);
    });
    rate.closest(".rq-item").classList.remove("is-missing");
    return;
  }
  const type = e.target.closest("[data-ri-type]");
  if (type) return openTypeDrawer(type.dataset.riType);
  const n = riasecStep();
  switch (e.target.closest("[data-ri]")?.dataset.ri) {
    case "exit":
      go("assessments");
      break;
    case "start":
    case "retake":
      Object.assign(r, { pages: buildPages(), answers: {}, missing: false });
      go("riasec/1");
      break;
    case "prev":
      r.missing = false;
      go(n > 1 ? `riasec/${n - 1}` : "riasec");
      break;
    case "next": {
      const done = r.pages[n - 1].every((key) => r.answers[key]);
      if (!done) {
        r.missing = true;
        renderRiasec(String(n));
        return riasecScreen.querySelector(".rq-item.is-missing")?.scrollIntoView({ behavior: "smooth", block: "center" });
      }
      r.missing = false;
      if (n < RIASEC_PAGES) return go(`riasec/${n + 1}`);
      r.result = scoreRiasec(r.answers);
      go("riasec/result");
      showToast("Assessment complete — your results are on your profile");
    }
  }
});

